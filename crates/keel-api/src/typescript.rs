//! TypeScript declarations generated from the operation registry's inlined JSON schemas.
use serde_json::Value;
use std::fmt::Write;

fn ty(s: &Value) -> String {
    if s == &Value::Bool(true) {
        return "unknown".into();
    }
    if s == &Value::Bool(false) {
        return "never".into();
    }
    assert!(s.get("$ref").is_none(), "SDK schemas must be inlined: {s}");
    if let Some(v) = s.get("const") {
        return v.to_string();
    }
    if let Some(values) = s.get("enum").and_then(Value::as_array) {
        return values
            .iter()
            .map(Value::to_string)
            .collect::<Vec<_>>()
            .join(" | ");
    }
    for (key, separator) in [("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")] {
        if let Some(values) = s.get(key).and_then(Value::as_array) {
            return format!(
                "({})",
                values.iter().map(ty).collect::<Vec<_>>().join(separator)
            );
        }
    }
    if let Some(values) = s.get("type").and_then(Value::as_array) {
        return values
            .iter()
            .map(|v| {
                let mut variant = s.clone();
                variant["type"] = v.clone();
                ty(&variant)
            })
            .collect::<Vec<_>>()
            .join(" | ");
    }
    match s.get("type").and_then(Value::as_str) {
        Some("null") => "null".into(),
        Some("boolean") => "boolean".into(),
        Some("integer" | "number") => "number".into(),
        Some("string") => "string".into(),
        Some("array") => {
            if let Some(items) = s.get("prefixItems").and_then(Value::as_array) {
                format!("[{}]", items.iter().map(ty).collect::<Vec<_>>().join(", "))
            } else {
                format!(
                    "Array<{}>",
                    s.get("items").map(ty).unwrap_or("unknown".into())
                )
            }
        }
        Some("object") => {
            let mut fields = Vec::new();
            if let Some(props) = s.get("properties").and_then(Value::as_object) {
                for (name, prop) in props {
                    let required = s
                        .get("required")
                        .and_then(Value::as_array)
                        .is_some_and(|r| r.contains(&Value::String(name.clone())));
                    fields.push(format!(
                        "{}{}: {}",
                        serde_json::to_string(name).unwrap(),
                        if required { "" } else { "?" },
                        ty(prop)
                    ));
                }
            }
            let object = format!("{{ {} }}", fields.join("; "));
            match s.get("additionalProperties") {
                Some(Value::Bool(false)) => object,
                Some(extra) => format!("{object} & Record<string, {}>", ty(extra)),
                None if fields.is_empty() => "Record<string, unknown>".into(),
                None => object,
            }
        }
        None => "unknown".into(),
        other => panic!("unsupported SDK schema type {other:?}: {s}"),
    }
}

/// Generate the complete SDK deterministically; no daemon or library is opened.
pub fn generate() -> String {
    let mut out = String::from(
        "// Generated by cargo run -p keel-api --example generate_typescript. Do not edit.\n\n",
    );
    let mut fingerprint = blake3::Hasher::new();
    for op in crate::OPS {
        fingerprint.update(op.name.as_bytes());
        fingerprint.update(&serde_json::to_vec(&(op.params)()).unwrap());
        fingerprint.update(&serde_json::to_vec(&(op.result)()).unwrap());
    }
    writeln!(
        out,
        "// API schema fingerprint: {}\n",
        fingerprint.finalize().to_hex()
    )
    .unwrap();
    out.push_str("export interface Operations {\n");
    for op in crate::OPS {
        writeln!(
            out,
            "  {:?}: {{ params: {}; result: {} }};",
            op.name,
            ty(&(op.params)()),
            ty(&(op.result)())
        )
        .unwrap();
    }
    out.push_str("}\n\n");
    out.push_str(include_str!("typescript_transport.txt"));
    out.push_str("\nexport class KeelClient extends RpcClient {\n");
    for op in crate::OPS {
        writeln!(out, "  /** {} */", op.summary.replace("*/", "* /")).unwrap();
        writeln!(out, "  {:?}(params: Operations[{:?}]['params']): Promise<Operations[{:?}]['result']> {{\n    return this.call({:?}, params);\n  }}", op.name, op.name, op.name, op.name).unwrap();
    }
    out.push_str("}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_client_matches_registry() {
        assert_eq!(
            generate(),
            include_str!("../../../sdk/typescript/keel.ts"),
            "run cargo run -p keel-api --example generate_typescript"
        );
    }

    #[test]
    fn schema_shapes() {
        let schema = serde_json::json!({"type":"object", "required":["kind"], "properties": {
            "kind":{"enum":["copy","move"]}, "count":{"type":["integer","null"]},
            "pair":{"type":"array","prefixItems":[{"type":"string"},{"type":"boolean"}]}
        }, "additionalProperties":false});
        assert_eq!(ty(&schema), "{ \"count\"?: number | null; \"kind\": \"copy\" | \"move\"; \"pair\"?: [string, boolean] }");
    }
}
